#!/usr/bin/env node
// Bundles each Edge Function (index.ts + ../_shared/*) into one self-contained ESM file under
// supabase/functions/.dist/<name>/index.ts for single-file deployment (e.g. via the Supabase MCP
// `deploy_edge_function` tool). npm:/jsr: imports stay external and are resolved by the runtime.
import { build } from 'esbuild';
import { mkdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const fnDir = join(root, 'supabase', 'functions');
const imports = JSON.parse(readFileSync(join(fnDir, 'deno.json'), 'utf8')).imports;
const functions = process.argv.slice(2).length ? process.argv.slice(2) : ['chat', 'data-delete', 'ingest-content'];

const denoSpecifiers = {
  name: 'deno-specifiers',
  setup(b) {
    b.onResolve({ filter: /^(npm|jsr|node):/ }, (args) => ({ path: args.path, external: true }));
    b.onResolve({ filter: /.*/ }, (args) => (imports[args.path] ? { path: imports[args.path], external: true } : undefined));
  },
};

for (const name of functions) {
  const outfile = join(fnDir, '.dist', name, 'index.ts');
  mkdirSync(join(fnDir, '.dist', name), { recursive: true });
  await build({
    entryPoints: [join(fnDir, name, 'index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    outfile,
    plugins: [denoSpecifiers],
    legalComments: 'none',
    banner: { js: `// GENERATED by scripts/bundle-functions.mjs from supabase/functions/${name} — edit the sources, not this file.\n// @ts-nocheck -- the sources are type-checked with deno check; this is bundled output.` },
    logLevel: 'warning',
  });
  console.log(`${name}: ${statSync(outfile).size} bytes -> ${outfile}`);
}
